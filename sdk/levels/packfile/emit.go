// Emit renders parsed packs as the Go source a cartridge compiles: one
// package-level `levels.Pack` var per pack, gofmt'd and deterministic for the
// same inputs. See [VarName] for the variable's name.
func Emit(pkg string, files []*File) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// SPDX-License-Identifier: GPL-2.0-or-later\n\n")
	b.WriteString("// Code generated by tools/genlevelpack; DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// The .arkadelevels pack files are the source of truth: edit those and\n")
	b.WriteString("// re-run the generator. Every level below parsed, and passed any hooks a\n")
	b.WriteString("// cartridge's own tools/genlevels applies; see sdk/levels/packfile for\n")
	b.WriteString("// the format and the hooks.\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	b.WriteString("import \"github.com/stealthmonkey99/arkade/sdk/levels\"\n")

	for _, f := range files {
		emitPack(&b, pkg, f)
	}

	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("generated source does not parse (this is a generator bug): %w", err)
	}
	return out, nil
}

func emitPack(b *strings.Builder, pkg string, f *File) {
	p := f.Pack
	ident := VarName(pkg, p.Name)

	fmt.Fprintf(b, "\n// %s is the %q pack: %d level(s) from %s.\n//\n",
		ident, p.Name, len(p.Levels), filepath.Base(f.Path))
	b.WriteString("// Legend:")
	for i, name := range p.Legend.Names {
		if i > 0 {
			b.WriteString(",")
		}
		fmt.Fprintf(b, " %s %s", quoteRune(p.Legend.Runes[i]), name)
	}
	b.WriteString(".\n")
	for i := range p.Legends {
		lg := &p.Legends[i]
		fmt.Fprintf(b, "// Legend %q:", lg.Name)
		for j, name := range lg.Names {
			if j > 0 {
				b.WriteString(",")
			}
			fmt.Fprintf(b, " %s %s", quoteRune(lg.Runes[j]), name)
		}
		b.WriteString(".\n")
	}

	fmt.Fprintf(b, "var %s = levels.Pack{\n", ident)
	fmt.Fprintf(b, "Name: %q,\n", p.Name)
	b.WriteString("Legend: levels.Legend{\n")
	emitLegend(b, &p.Legend)
	if len(p.Legends) > 0 {
		b.WriteString("Legends: []levels.Legend{\n")
		for i := range p.Legends {
			b.WriteString("{\n")
			emitLegend(b, &p.Legends[i])
		}
		b.WriteString("},\n")
	}

	b.WriteString("Levels: []levels.Level{\n")
	for i := range p.Levels {
		emitLevel(b, &p.Levels[i])
	}
	b.WriteString("},\n}\n")
}

// emitLegend writes a legend literal's body and closing brace; the caller opens
// the literal, since a slice element elides the type name and a struct field
// does not. Name and Values are omitted when empty.
func emitLegend(b *strings.Builder, lg *levels.Legend) {
	if lg.Name != "" {
		fmt.Fprintf(b, "Name: %q,\n", lg.Name)
	}
	fmt.Fprintf(b, "Runes: %q,\nNames: []string{", lg.Runes)
	for i, name := range lg.Names {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(b, "%q", name)
	}
	b.WriteString("},\n")
	if len(lg.Values) > 0 {
		b.WriteString("Values: levels.Args{\n")
		for i, v := range lg.Values {
			emitValue(b, v, " // "+quoteRune(lg.Runes[i])+" "+lg.Names[i])
		}
		b.WriteString("},\n")
	}
	b.WriteString("},\n")
}

func emitLevel(b *strings.Builder, lv *levels.Level) {
	fmt.Fprintf(b, "{\nName: %q, W: %d, H: %d,\n", lv.Name, lv.W, lv.H)
	emitCells(b, "Cells", lv.W, lv.H, lv.Cells)

	if len(lv.Layers) > 0 {
		b.WriteString("Layers: []levels.Layer{\n")
		for i := range lv.Layers {
			ly := &lv.Layers[i]
			fmt.Fprintf(b, "{\nName: %q, ", ly.Name)
			if ly.Legend != "" {
				fmt.Fprintf(b, "Legend: %q, ", ly.Legend)
			}
			fmt.Fprintf(b, "W: %d, H: %d,\n", ly.W, ly.H)
			emitCells(b, "Cells", ly.W, ly.H, ly.Cells)
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}

	if len(lv.Records) > 0 {
		b.WriteString("Records: []levels.Record{\n")
		for i := range lv.Records {
			r := &lv.Records[i]
			fmt.Fprintf(b, "{Kind: %q, X: %d, Y: %d", r.Kind, r.X, r.Y)
			if len(r.Args) > 0 {
				b.WriteString(", Args: levels.Args{\n")
				for _, v := range r.Args {
					emitValue(b, v, "")
				}
				b.WriteString("}")
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}

	if len(lv.Exits) > 0 {
		b.WriteString("Exits: []levels.Exit{\n")
		for i := range lv.Exits {
			e := &lv.Exits[i]
			fmt.Fprintf(b, "{Dir: %q, Target: %d", e.Dir, e.Target)
			if len(e.Locks) > 0 {
				b.WriteString(", Locks: levels.Args{\n")
				for _, v := range e.Locks {
					emitValue(b, v, "")
				}
				b.WriteString("}")
			}
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
	}

	if len(lv.Meta) > 0 {
		b.WriteString("Meta: []levels.Entry{\n")
		for _, e := range lv.Meta {
			switch e.Kind {
			case levels.KindStr:
				fmt.Fprintf(b, "{Key: %q, Kind: levels.KindStr, Str: %q},\n", e.Key, e.Str)
			case levels.KindBool:
				fmt.Fprintf(b, "{Key: %q, Kind: levels.KindBool, Int: %d}, // %v\n", e.Key, e.Int, e.Int != 0)
			case levels.KindColor:
				fmt.Fprintf(b, "{Key: %q, Kind: levels.KindColor, Int: 0x%06x},\n", e.Key, e.Int)
			default:
				fmt.Fprintf(b, "{Key: %q, Int: %d},\n", e.Key, e.Int)
			}
		}
		b.WriteString("},\n")
	}
	b.WriteString("},\n")
}

func emitValue(b *strings.Builder, v levels.Value, note string) {
	switch v.Kind {
	case levels.KindStr:
		fmt.Fprintf(b, "{Kind: levels.KindStr, Str: %q},", v.Str)
	case levels.KindBool:
		fmt.Fprintf(b, "{Kind: levels.KindBool, Int: %d},", v.Int)
	case levels.KindColor:
		fmt.Fprintf(b, "{Kind: levels.KindColor, Int: 0x%06x},", v.Int)
	case levels.KindNone:
		b.WriteString("{Kind: levels.KindNone},")
	default:
		fmt.Fprintf(b, "{Int: %d},", v.Int)
	}
	b.WriteString(note)
	b.WriteString("\n")
}

// emitCells writes a grid as one row per line, concatenated with "+". Go folds
// that to a single string constant, so nothing runs at startup.
func emitCells(b *strings.Builder, field string, w, h int, cells string) {
	fmt.Fprintf(b, "%s: ", field)
	for y := 0; y < h; y++ {
		if y > 0 {
			b.WriteString(" +\n")
		}
		b.WriteString(strconv.Quote(cells[y*w : (y+1)*w]))
	}
	b.WriteString(",\n")
}

// VarName is the identifier Emit gives a pack: the pack's name in camel case
// plus a "Pack" suffix, so `pack bonus-rooms` becomes bonusRoomsPack. It is
// exported unless pkg is "main".
func VarName(pkg, pack string) string {
	var b strings.Builder
	upper := pkg != "main"
	for i := 0; i < len(pack); i++ {
		c := pack[i]
		if c == '-' || c == '_' {
			upper = true
			continue
		}
		if upper {
			if c >= 'a' && c <= 'z' {
				c -= 'a' - 'A'
			}
			upper = false
		}
		b.WriteByte(c)
	}
	return b.String() + "Pack"
}
