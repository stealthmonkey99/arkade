const fullManifest = `{
  "schemaVersion": 1,
  "abi": 1,
  "slug": "fixture",
  "title": "Fixture & Friends",
  "publisher": "arkade",
  "version": "1.1.3",
  "description": "One edge at a time — then it snowballs.",
  "tags": ["puzzle"],
  "players": ["1p", "2p-versus"],
  "audience": "all-ages",
  "capabilities": [],
  "visibility": "public",
  "icon": "assets/icon.arkadesprite.png",
  "links": { "source": null }
}
`

const fullSource = "// SPDX-License-Identifier: GPL-2.0-or-later\n" +
	"\n" +
	"// Code generated by manifestgen from manifest.json. DO NOT EDIT.\n" +
	"\n" +
	"package main\n" +
	"\n" +
	"const manifestJSON = `{\"abi\":1,\"slug\":\"fixture\",\"name\":\"Fixture & Friends\",\"description\":\"One edge at a time — then it snowballs.\",\"version\":\"1.1.3\",\"players\":[1,2],\"icon\":\"assets/icon.arkadesprite.png\"}`\n" +
	"\n" +
	"var manifestBytes = []byte(manifestJSON)\n"

func TestSourceIsTheExactFile(t *testing.T) {
	got, err := Source([]byte(fullManifest))
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != fullSource {
		t.Errorf("Source =\n%s\nwant\n%s", got, fullSource)
	}
}

func TestRuntimeMapsTheBundleSchema(t *testing.T) {
	for _, tc := range []struct {
		name, manifest, want string
	}{
		{"modes become the counts they support",
			`{"abi":1,"slug":"x","title":"X","version":"1.0.0","players":["2p-versus","alternating"]}`,
			`{"abi":1,"slug":"x","name":"X","description":"","version":"1.0.0","players":[2]}`},
		{"counts are sorted whatever the mode order",
			`{"abi":1,"slug":"x","title":"X","version":"1.0.0","players":["alternating","1p"]}`,
			`{"abi":1,"slug":"x","name":"X","description":"","version":"1.0.0","players":[1,2]}`},
		{"legacy integer players pass through",
			`{"abi":1,"slug":"x","title":"X","version":"1.0.0","players":[1,2]}`,
			`{"abi":1,"slug":"x","name":"X","description":"","version":"1.0.0","players":[1,2]}`},
		{"a legacy name stands in for the title",
			`{"abi":1,"slug":"x","name":"Old","version":"1.0.0","players":["1p"]}`,
			`{"abi":1,"slug":"x","name":"Old","description":"","version":"1.0.0","players":[1]}`},
		{"rawDirections is carried only when set",
			`{"abi":1,"slug":"x","title":"X","version":"1.0.0","players":["1p"],"rawDirections":true}`,
			`{"abi":1,"slug":"x","name":"X","description":"","version":"1.0.0","players":[1],"rawDirections":true}`},
		{"html characters stay themselves",
			`{"abi":1,"slug":"x","title":"A <b> & c","version":"1.0.0","players":["1p"]}`,
			`{"abi":1,"slug":"x","name":"A <b> & c","description":"","version":"1.0.0","players":[1]}`},
	} {
		got, err := Runtime([]byte(tc.manifest))
		if err != nil {
			t.Errorf("%s: %v", tc.name, err)
			continue
		}
		if string(got) != tc.want {
			t.Errorf("%s:\n got %s\nwant %s", tc.name, got, tc.want)
		}
	}
}

func TestRuntimeRefusesAnIncompleteManifest(t *testing.T) {
	for _, tc := range []struct{ name, manifest, want string }{
		{"no abi", `{"slug":"x","title":"X","version":"1.0.0","players":["1p"]}`, `"abi"`},
		{"no slug", `{"abi":1,"title":"X","version":"1.0.0","players":["1p"]}`, `"slug"`},
		{"no title", `{"abi":1,"slug":"x","version":"1.0.0","players":["1p"]}`, `"title"`},
		{"no version", `{"abi":1,"slug":"x","title":"X","players":["1p"]}`, `"version"`},
		{"no players", `{"abi":1,"slug":"x","title":"X","version":"1.0.0"}`, `"players"`},
		{"not json", `{`, "manifest.json"},
	} {
		_, err := Runtime([]byte(tc.manifest))
		if err == nil || !strings.Contains(err.Error(), tc.want) {
			t.Errorf("%s: err = %v, want it to name %s", tc.name, err, tc.want)
		}
	}
}

func TestSourceQuotesABacktick(t *testing.T) {
	got, err := Source([]byte(`{"abi":1,"slug":"x","title":"X","version":"1.0.0","players":["1p"],"description":"a ` + "`tick`" + `"}`))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(got), "const manifestJSON = \"{") {
		t.Errorf("a backtick must switch the literal to interpreted form:\n%s", got)
	}
}

func TestWriteIsIdempotentAndCheckSeesDrift(t *testing.T) {
	dir := t.TempDir()
	manifest := filepath.Join(dir, ManifestName)
	if err := os.WriteFile(manifest, []byte(fullManifest), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := Check(dir); err == nil || !strings.Contains(err.Error(), "no "+FileName) {
		t.Errorf("Check before any Write = %v, want the missing file named", err)
	}

	changed, err := Write(dir)
	if err != nil || !changed {
		t.Fatalf("first Write = %v, %v, want a write", changed, err)
	}
	got, err := os.ReadFile(filepath.Join(dir, FileName))
	if err != nil || string(got) != fullSource {
		t.Fatalf("written file =\n%s\nwant\n%s (%v)", got, fullSource, err)
	}
	if changed, err := Write(dir); err != nil || changed {
		t.Errorf("second Write = %v, %v, want a no-op", changed, err)
	}
	if err := Check(dir); err != nil {
		t.Errorf("Check after Write = %v", err)
	}

	bumped := strings.Replace(fullManifest, `"1.1.3"`, `"1.2.0"`, 1)
	if err := os.WriteFile(manifest, []byte(bumped), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := Check(dir); err == nil || !strings.Contains(err.Error(), "stale") {
		t.Errorf("Check after a version bump = %v, want stale", err)
	}
	if changed, err := Write(dir); err != nil || !changed {
		t.Errorf("Write after a version bump = %v, %v, want a write", changed, err)
	}
	if err := Check(dir); err != nil {
		t.Errorf("Check after regenerating = %v", err)
	}
}
