// Package gen derives a cartridge's runtime manifest, the JSON cart_manifest
// returns, from its manifest.json and writes it as manifest_gen.go. The
// bundle manifest is the only file an author edits; this package is where
// its schema (title, player modes) becomes the ABI's (name, player counts).
package gen

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strconv"

	"github.com/stealthmonkey99/arkade/internal/cartridge/rcart"
)

// FileName is the generated source file, beside manifest.json.
const FileName = "manifest_gen.go"

// ManifestName is the bundle manifest the runtime manifest derives from.
const ManifestName = "manifest.json"

// runtimeManifest is the cart_manifest payload (docs/CARTRIDGE.md,
// "Manifest"); the field order is the emitted key order.
type runtimeManifest struct {
	ABI           int    `json:"abi"`
	Slug          string `json:"slug"`
	Name          string `json:"name"`
	Description   string `json:"description"`
	Version       string `json:"version"`
	Players       []int  `json:"players"`
	Icon          string `json:"icon,omitempty"`
	RawDirections bool   `json:"rawDirections,omitempty"`
}

// Runtime returns the compact cart_manifest JSON for a bundle manifest:
// abi, slug, description, version and icon as given, name from the title,
// players as the counts the declared modes support, and rawDirections only
// when set.
func Runtime(manifest []byte) ([]byte, error) {
	var m rcart.Manifest
	if err := json.Unmarshal(manifest, &m); err != nil {
		return nil, fmt.Errorf("%s: %w", ManifestName, err)
	}
	for _, req := range []struct {
		field string
		ok    bool
	}{
		{"abi", m.ABI > 0},
		{"slug", m.Slug != ""},
		{"title", m.DisplayTitle() != ""},
		{"version", m.Version != ""},
		{"players", len(m.Players) > 0},
	} {
		if !req.ok {
			return nil, fmt.Errorf("%s: %q is required", ManifestName, req.field)
		}
	}
	var players []int
	for _, n := range []int{1, 2} {
		if m.Players.SupportsCount(n) {
			players = append(players, n)
		}
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(runtimeManifest{
		ABI:           m.ABI,
		Slug:          m.Slug,
		Name:          m.DisplayTitle(),
		Description:   m.Description,
		Version:       m.Version,
		Players:       players,
		Icon:          m.Icon,
		RawDirections: m.RawDirections,
	}); err != nil {
		return nil, err
	}
	return bytes.TrimRight(buf.Bytes(), "\n"), nil
}

const source = `// SPDX-License-Identifier: GPL-2.0-or-later

// Code generated by manifestgen from manifest.json. DO NOT EDIT.

package main

const manifestJSON = %s

var manifestBytes = []byte(manifestJSON)
`

// Source returns the contents of manifest_gen.go for a bundle manifest: a
// package-main file declaring the manifestJSON constant and the
// manifestBytes slice a Game's Manifest method returns.
func Source(manifest []byte) ([]byte, error) {
	rt, err := Runtime(manifest)
	if err != nil {
		return nil, err
	}
	lit := "`" + string(rt) + "`"
	if bytes.ContainsRune(rt, '`') {
		lit = strconv.Quote(string(rt))
	}
	return []byte(fmt.Sprintf(source, lit)), nil
}

// Write regenerates dir's manifest_gen.go from its manifest.json and
// reports whether the file changed. An up-to-date file is left untouched.
func Write(dir string) (changed bool, err error) {
	want, err := want(dir)
	if err != nil {
		return false, err
	}
	path := filepath.Join(dir, FileName)
	if have, err := os.ReadFile(path); err == nil && bytes.Equal(have, want) {
		return false, nil
	}
	return true, os.WriteFile(path, want, 0o644)
}

// Check reports an error when dir's manifest_gen.go is missing or differs
// from what its manifest.json generates.
func Check(dir string) error {
	want, err := want(dir)
	if err != nil {
		return err
	}
	have, err := os.ReadFile(filepath.Join(dir, FileName))
	switch {
	case errors.Is(err, os.ErrNotExist):
		return fmt.Errorf("no %s", FileName)
	case err != nil:
		return err
	case !bytes.Equal(have, want):
		return fmt.Errorf("%s is stale against %s", FileName, ManifestName)
	}
	return nil
}

func want(dir string) ([]byte, error) {
	manifest, err := os.ReadFile(filepath.Join(dir, ManifestName))
	if err != nil {
		return nil, err
	}
	return Source(manifest)
}
