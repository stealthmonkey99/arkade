package main

import (
	"bytes"
	"os/exec"
	"path/filepath"
	"strings"

	"github.com/stealthmonkey99/arkade/sdk/levels/packfile"
)

const ruleLevels = "the assets/*.arkadelevels pack files are the source: levels_gen.go is build output, regenerated by every cartridge build (tools/genlevelpack, or the cartridge's own tools/genlevels) and committed like manifest_gen.go, so it must be current"

// checkGeneratedLevels requires the generated level files to be what the
// cartridge's pack files generate. A cartridge with its own generator is
// asked through its -check, since its hooks live in its own module.
func checkGeneratedLevels(c *Cart, r *Result) {
	levelsDir := filepath.Join(c.Dir, packfile.AssetsDir)
	ok, err := packfile.HasPacks(c.Dir)
	if err != nil {
		r.fail(ruleLevels, c.At(levelsDir), "%v", err)
		return
	}
	if !ok {
		r.summarize("no level packs")
		return
	}
	fix := "regenerate with `make build`, or `go run ./tools/genlevelpack " + c.Rel(c.Dir) + "` from the engine"

	if packfile.HasGenerator(c.Dir) {
		cmd := exec.Command("go", "run", "./"+packfile.GeneratorDir, "-check")
		cmd.Dir = c.Dir
		var stderr bytes.Buffer
		cmd.Stderr = &stderr
		if err := cmd.Run(); err != nil {
			msg := strings.TrimSpace(stderr.String())
			if msg == "" {
				msg = err.Error()
			}
			r.fail(ruleLevels, c.At(levelsDir), "%s -check: %s — %s", packfile.GeneratorDir, msg, fix)
			return
		}
		r.summarize("generated level files current (%s -check)", packfile.GeneratorDir)
		return
	}

	if err := packfile.Check(packfile.CartridgeConfig(c.Dir)); err != nil {
		r.fail(ruleLevels, c.At(filepath.Join(c.Dir, packfile.GenFile)), "%v — %s", err, fix)
		return
	}
	r.summarize("%s current", packfile.GenFile)
}
