// Package loopcert gives devserve and assetbridge an HTTPS certificate for
// the loopback names only, for browsers (Safari) that block an https page
// from calling http://127.0.0.1. It is a self-signed leaf, not a CA: trusting
// it vouches for localhost, 127.0.0.1 and ::1 and nothing else.
package loopcert

import (
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/pem"
	"fmt"
	"math/big"
	"net"
	"os"
	"path/filepath"
	"time"
)

// Apple refuses TLS server certificates valid for longer than 825 days.
const lifetime = 825 * 24 * time.Hour

const renewBefore = 30 * 24 * time.Hour

var dnsNames = []string{"localhost"}

var ipAddrs = []net.IP{net.IPv4(127, 0, 0, 1), net.IPv6loopback}

// Cert is the loaded certificate and where its PEM lives.
type Cert struct {
	TLS      tls.Certificate
	CertPath string
	Created  bool // generated by this call, so the browser does not trust it yet
}

// DefaultDir is where both tools share one certificate, so it is trusted once.
func DefaultDir() (string, error) {
	base, err := os.UserConfigDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(base, "arkade", "loopback-tls"), nil
}

// LoadDefault is Load on DefaultDir.
func LoadDefault() (Cert, error) {
	dir, err := DefaultDir()
	if err != nil {
		return Cert{}, err
	}
	return Load(dir)
}

// Load returns the certificate in dir, making a new one when it is missing,
// unreadable, missing a loopback name, or within 30 days of expiry.
func Load(dir string) (Cert, error) {
	certPath := filepath.Join(dir, "cert.pem")
	keyPath := filepath.Join(dir, "key.pem")
	if c, err := tls.LoadX509KeyPair(certPath, keyPath); err == nil && usable(c, time.Now()) {
		return Cert{TLS: c, CertPath: certPath}, nil
	}
	certPEM, keyPEM, err := generate(time.Now())
	if err != nil {
		return Cert{}, err
	}
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return Cert{}, err
	}
	if err := os.WriteFile(keyPath, keyPEM, 0o600); err != nil {
		return Cert{}, err
	}
	if err := os.WriteFile(certPath, certPEM, 0o644); err != nil {
		return Cert{}, err
	}
	c, err := tls.X509KeyPair(certPEM, keyPEM)
	if err != nil {
		return Cert{}, err
	}
	return Cert{TLS: c, CertPath: certPath, Created: true}, nil
}

func usable(c tls.Certificate, now time.Time) bool {
	if len(c.Certificate) == 0 {
		return false
	}
	leaf, err := x509.ParseCertificate(c.Certificate[0])
	if err != nil || now.Add(renewBefore).After(leaf.NotAfter) {
		return false
	}
	for _, name := range dnsNames {
		if leaf.VerifyHostname(name) != nil {
			return false
		}
	}
	for _, ip := range ipAddrs {
		if leaf.VerifyHostname(ip.String()) != nil {
			return false
		}
	}
	return true
}

func generate(now time.Time) (certPEM, keyPEM []byte, err error) {
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return nil, nil, err
	}
	serial, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 128))
	if err != nil {
		return nil, nil, err
	}
	tmpl := &x509.Certificate{
		SerialNumber:          serial,
		Subject:               pkix.Name{CommonName: "Arkade loopback", Organization: []string{"Arkade local tools"}},
		NotBefore:             now.Add(-time.Hour),
		NotAfter:              now.Add(lifetime),
		KeyUsage:              x509.KeyUsageDigitalSignature,
		ExtKeyUsage:           []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
		BasicConstraintsValid: true,
		IsCA:                  false,
		DNSNames:              dnsNames,
		IPAddresses:           ipAddrs,
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
	if err != nil {
		return nil, nil, err
	}
	keyDER, err := x509.MarshalPKCS8PrivateKey(key)
	if err != nil {
		return nil, nil, err
	}
	return pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}),
		pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: keyDER}), nil
}

// Config is a server config serving c.
func (c Cert) Config() *tls.Config {
	return &tls.Config{Certificates: []tls.Certificate{c.TLS}, MinVersion: tls.VersionTLS12}
}

// TrustHint tells the user how to make their browser accept the certificate.
func (c Cert) TrustHint() string {
	return fmt.Sprintf(`trust it once so the browser accepts it (macOS asks for your password):
  security add-trusted-cert -p ssl -k ~/Library/Keychains/login.keychain-db %q`, c.CertPath)
}
